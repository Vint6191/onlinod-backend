"use strict";

const SFS_MODULE_KEY = "sfs";
const SFS_DISCOVERY_JOB_KEY = "sfs_target_discovery";
const SFS_TARGET_SCAN_JOB_KEY = "sfs_target_scan";
const SFS_FOLLOW_TARGET_ACTION_TYPE = "SFS_FOLLOW_TARGET";
const SFS_COMMENT_POST_ACTION_TYPE = "SFS_COMMENT_POST";
const SFS_LIKE_COMMENT_ACTION_TYPE = "SFS_LIKE_COMMENT";
const SFS_UNFOLLOW_TARGET_ACTION_TYPE = "SFS_UNFOLLOW_TARGET";
const SFS_ACTION_TYPES = Object.freeze([
  SFS_FOLLOW_TARGET_ACTION_TYPE,
  SFS_COMMENT_POST_ACTION_TYPE,
  SFS_LIKE_COMMENT_ACTION_TYPE,
  SFS_UNFOLLOW_TARGET_ACTION_TYPE,
]);

function isSfsCleanupDelivery(delivery) {
  return delivery?.moduleKey === SFS_MODULE_KEY && delivery?.actionType === SFS_UNFOLLOW_TARGET_ACTION_TYPE;
}

module.exports = {
  SFS_MODULE_KEY,
  SFS_DISCOVERY_JOB_KEY,
  SFS_TARGET_SCAN_JOB_KEY,
  SFS_FOLLOW_TARGET_ACTION_TYPE,
  SFS_COMMENT_POST_ACTION_TYPE,
  SFS_LIKE_COMMENT_ACTION_TYPE,
  SFS_UNFOLLOW_TARGET_ACTION_TYPE,
  SFS_ACTION_TYPES,
  isSfsCleanupDelivery,
};
